"""JSON file storage for LessonPrep.

Layout (see proposal, section 8):
  data/tutors.json            every tutor's account + public profile
  data/tutors/<tutor_id>.json that tutor's private data: students, trial requests
                              (later: lessons, difficulty tags, tasks, plans)

This module is the only place that reads or writes files, so the rest of
the app never touches the disk directly.
"""
import json
import os
import re
import threading
import uuid
from datetime import datetime, timezone

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
TUTORS_FILE = os.path.join(DATA_DIR, "tutors.json")
TUTOR_DIR = os.path.join(DATA_DIR, "tutors")

# Tutor ids are UUIDs generated by the server. Any other value is rejected
# before it is used in a file path (blocks path traversal like "../../x").
UUID_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")

# One lock for all writes: Flask can handle two requests at the same time,
# and without a lock two writes could overwrite each other.
_lock = threading.Lock()


def _load(path, default):
    """Read a JSON file. Missing or corrupted file -> default value
    (the app must never crash on bad data)."""
    if not os.path.exists(path):
        return default
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, type(default)) else default
    except (json.JSONDecodeError, OSError):
        return default


def _save(path, data):
    """Write to a temporary file first, then replace the real file.
    If the app crashes mid-write, the old file is still intact."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp_path = path + ".tmp"
    with open(tmp_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    os.replace(tmp_path, path)


def _tutor_file(tutor_id):
    if not UUID_RE.match(tutor_id or ""):
        raise ValueError("invalid tutor id")
    return os.path.join(TUTOR_DIR, f"{tutor_id}.json")


def _empty_workspace():
    return {"students": [], "trial_requests": []}


def _now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


# ---------- Tutors (accounts + public profile) ----------

def find_tutor_by_email(email):
    for tutor in _load(TUTORS_FILE, []):
        if tutor["email"] == email:
            return tutor
    return None


def find_tutor_by_id(tutor_id):
    if not UUID_RE.match(tutor_id or ""):
        return None
    for tutor in _load(TUTORS_FILE, []):
        if tutor["id"] == tutor_id:
            return tutor
    return None


def create_tutor(name, email, password_hash):
    """Add a tutor. Returns the new tutor, or None if the email is taken."""
    with _lock:
        tutors = _load(TUTORS_FILE, [])
        if any(t["email"] == email for t in tutors):
            return None
        tutor = {
            "id": str(uuid.uuid4()),
            "name": name,
            "email": email,
            "password_hash": password_hash,  # never the plain password
            "profile": {"languages": "", "levels": [], "philosophy": ""},
        }
        tutors.append(tutor)
        _save(TUTORS_FILE, tutors)
        _save(_tutor_file(tutor["id"]), _empty_workspace())
        return tutor


def update_profile(tutor_id, languages, levels, philosophy):
    with _lock:
        tutors = _load(TUTORS_FILE, [])
        for t in tutors:
            if t["id"] == tutor_id:
                t["profile"] = {"languages": languages, "levels": levels,
                                "philosophy": philosophy}
                _save(TUTORS_FILE, tutors)
                return True
        return False


# ---------- Private workspace (one file per tutor) ----------
# Every function takes the tutor_id from the session, so a tutor can only
# ever open their own file: this is the per-user data isolation.

def list_students(tutor_id):
    return _load(_tutor_file(tutor_id), _empty_workspace()).get("students", [])


def create_student(tutor_id, name, language, level, goal):
    with _lock:
        path = _tutor_file(tutor_id)
        ws = _load(path, _empty_workspace())
        student = {
            "id": str(uuid.uuid4()),
            "tutor_id": tutor_id,
            "name": name,
            "language": language,
            "level": level,
            "goal": goal,
            "created_at": _now(),
        }
        ws.setdefault("students", []).append(student)
        _save(path, ws)
        return student


def list_trial_requests(tutor_id):
    return _load(_tutor_file(tutor_id), _empty_workspace()).get("trial_requests", [])


def add_trial_request(tutor_id, name, email, message):
    """Called from the PUBLIC profile page: a visitor writes into one
    tutor's inbox, but can never read it."""
    with _lock:
        path = _tutor_file(tutor_id)
        ws = _load(path, _empty_workspace())
        ws.setdefault("trial_requests", []).append({
            "id": str(uuid.uuid4()),
            "name": name,
            "email": email,
            "message": message,
            "created_at": _now(),
        })
        _save(path, ws)
